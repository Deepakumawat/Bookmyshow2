export const getEventsByCategory = (category) => {
  return mockEvents[category] || [];
};

export const getAllEvents = () => {
  return [
    ...mockEvents.movies,
    ...mockEvents.events,
    ...mockEvents.plays,
    ...mockEvents.sports,
    ...mockEvents.streaming,
  ];
};

export const getEventById = (category, eventId) => {
  const events = mockEvents[category] || [];
  return events.find((event) => event.id === eventId);
};

export const findEventById = (eventId) => {
  const allEvents = getAllEvents();
  return allEvents.find((event) => event.id === eventId);
};

export const searchEvents = (query, category) => {
  const events = mockEvents[category] || [];
  const lowerQuery = query.toLowerCase();
  return events.filter((event) => {
    const genres = Array.isArray(event.genres) ? event.genres.join(' ') : event.genres || '';
    return (
      event.title.toLowerCase().includes(lowerQuery) ||
      genres.toLowerCase().includes(lowerQuery) ||
      (event.description && event.description.toLowerCase().includes(lowerQuery))
    );
  });
};
